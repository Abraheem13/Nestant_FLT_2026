"""
gen_tex.py -- write every number used in the paper from results/summary.json.

Outputs (in results/tex/ unless a directory is given):
    numbers.tex  macros  \\V{cfg}{method}{metric}  mean
                         \\D{cfg}{method}{metric}  sample std
                         \\PM{cfg}{method}{metric} "mean \\pm std"
                         plus a few scalar macros (tests, data facts)
    tab_t5.tex, tab_long.tex (T=10 and T=20), tab_budget.tex
"""
import json
import sys

import numpy as np
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
S = json.loads((ROOT / "results" / "summary.json").read_text())
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "results" / "tex"
OUT.mkdir(parents=True, exist_ok=True)

DEC = {"s11_r2": 3, "gain_r2": 3, "fr_r2": 3, "s11_mae": 2, "s11_mae_matched": 2, "gain_mae": 2,
       "fr_mape": 2, "matched_pooled": 2, "worst_drop": 2, "median_drop": 2}


def dec(metric):
    for k, d in DEC.items():
        if metric.endswith(k):
            return d
    return 3


def fmt(x, d):
    s = f"{x:.{d}f}"
    if s.startswith("-"):
        s = "-" + s[1:]
    if float(s) == 0:
        s = s.lstrip("-")
    return s


lines = [r"% generated by code/src/gen_tex.py from results/summary.json -- do not edit",
         r"\makeatletter",
         r"\newcommand{\V}[3]{\@nameuse{v@#1@#2@#3}}",
         r"\newcommand{\D}[3]{\@nameuse{d@#1@#2@#3}}",
         r"\newcommand{\PM}[3]{\@nameuse{v@#1@#2@#3}\ensuremath{\,\pm\,}\@nameuse{d@#1@#2@#3}}",
         r"\newcommand{\X}[1]{\@nameuse{x@#1}}"]


def put(kind, key, val):
    lines.append(rf"\@namedef{{{kind}@{key}}}{{{val}}}")


for cfg, methods in S.items():
    if not cfg.startswith("T"):
        continue
    for name, v in methods.items():
        if not isinstance(v, dict):
            continue
        for metric, st in v.items():
            if isinstance(st, dict) and "mean" in st and "std" in st:
                d = dec(metric)
                put("v", f"{cfg}@{name}@{metric}", "\\ensuremath{" + fmt(st["mean"], d) + "}")
                put("d", f"{cfg}@{name}@{metric}", "\\ensuremath{" + fmt(st["std"], d) + "}")
        if v.get("params") is not None:
            put("v", f"{cfg}@{name}@params", f"{v['params']:,}".replace(",", "{,}"))
        if "seconds" in v:
            put("v", f"{cfg}@{name}@sec", f"{v['seconds']['mean']:.0f}")

for k, t in S["tests"].items():
    key = k.replace(":", "@")
    if t["p"] >= 1e-3:
        pv = f"{t['p']:.2g}"
    else:
        e = int(np.floor(np.log10(t["p"]))); pv = f"\\ensuremath{{{t['p'] / 10 ** e:.1f}\\times10^{{{e}}}}}"
    put("x", f"{key}@p", pv)
    d = 3 if k.endswith("r2") else 2
    put("x", f"{key}@diff", "\\ensuremath{" + fmt(t["diff"], d) + "}")
    put("x", f"{key}@absdiff", fmt(abs(t["diff"]), d))

D = S["data"]
put("x", "rows", f"{D['rows']:,}".replace(",", "{,}"))
put("x", "geoms", f"{D['geometries']:,}".replace(",", "{,}"))
put("x", "repsdmed", f"{D['s11_rep_sd_median']:.2f}")
put("x", "repsdmean", f"{D['s11_rep_sd_mean']:.2f}")
put("x", "matched", f"{100 * D['matched_frac']:.1f}")
put("x", "posrows", str(D["s11_positive_rows"]))
for T in (5, 10, 20):
    c = D["ceiling"][f"T{T}"]
    put("x", f"ceilT{T}", f"{c['mean']:.3f}")
    put("x", f"ceilT{T}min", f"{min(c['per_task']):.3f}")
    put("x", f"ceilT{T}max", f"{max(c['per_task']):.3f}")
    put("x", f"ceilmaeT{T}", f"{c['mae_mean']:.2f}")
    put("x", f"sdminT{T}", f"{min(c['s11_sd_per_task']):.2f}")
for cfg in S:
    if cfg.startswith("T") and "ewc_best" in S[cfg]:
        lam = float(S[cfg]["ewc_best"]["selected"].replace("ewc_lam", ""))
        e = int(round(__import__("math").log10(lam)))
        put("x", f"lam@{cfg}", f"10^{{{e}}}" if lam != 1 else "1")
for T in (5, 10, 20):
    r = D["train_rows"][f"T{T}"]
    put("x", f"trainminT{T}", f"{r['min']:,}".replace(",", "{,}"))
    put("x", f"trainmaxT{T}", f"{r['max']:,}".replace(",", "{,}"))
put("x", "nruns", str(S["compute"]["n_runs"]))
for T in (5, 10, 20):
    put("x", f"ratioT{T}", f"{S[f'T{T}_e300']['prognet']['params'] / S[f'T{T}_e300']['cms']['params']:.1f}")
put("x", "cpuh", f"{S['compute']['cpu_hours']:.1f}")
g = S["gradient_check"]; e = int(np.floor(np.log10(g))); mant = g / 10 ** e
put("x", "gradmax", f"\\ensuremath{{{mant:.1f}\\times10^{{{e}}}}}")
lines.append(r"\makeatother")
(OUT / "numbers.tex").write_text("\n".join(lines) + "\n")


# ------------------------------------------------------------------ tables
def pm(cfg, m, metric):
    st = S[cfg][m][metric]; d = dec(metric)
    return f"${fmt(st['mean'], d)}\\pm{fmt(st['std'], d)}$"


def mn(cfg, m, metric):
    return f"${fmt(S[cfg][m][metric]['mean'], dec(metric))}$"


def params(cfg, m):
    p = S[cfg][m].get("params")
    return f"{p:,}".replace(",", "{,}") if p else "--"


ROWS = [("xgb", "XGBoost, refit"), ("rf", "Random forest, refit"),
        ("finetune", "MLP, fine-tuned"), ("ewc_best", "EWC, best $\\lambda$"),
        ("replay_buf0.1", "Replay, 10\\,\\%"), ("indep", "Independent MLPs"),
        ("cms", "NestAnt-CMS"), ("prognet", "Progressive Nets")]
POOLED = (("joint_xgb", "XGBoost, pooled$^\\ast$"), ("joint_mlp", "MLP, pooled$^\\ast$"))


cfg = "T5_e300"
t = [r"\begin{tabular}{@{}lcccccccr@{}}", r"\toprule",
     r" & \multicolumn{3}{c}{$S_{11}$ MAE (dB)} & \multicolumn{3}{c}{$S_{11}$ $R^2$} & Gain MAE & $f_r$ err. & \\",
     r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
     r"Method & Diag.\,$\downarrow$ & Final\,$\downarrow$ & $\Delta$\,$\downarrow$ & Diag.\,$\uparrow$ & Final\,$\uparrow$ & BWT\,$\uparrow$ & (dB)\,$\downarrow$ & (\%)\,$\downarrow$ & Params \\",
     r"\midrule"]
t[0] = r"\begin{tabular}{@{}lccccccccr@{}}"
for k, lab in ROWS:
    t.append(f"{lab} & {mn(cfg, k, 'diag_s11_mae')} & {pm(cfg, k, 'final_s11_mae')} & {mn(cfg, k, 'bwt_s11_mae')} & "
             f"{mn(cfg, k, 'diag_s11_r2')} & {pm(cfg, k, 'final_s11_r2')} & {mn(cfg, k, 'bwt_s11_r2')} & "
             f"{mn(cfg, k, 'final_gain_mae')} & {mn(cfg, k, 'final_fr_mape')} & {params(cfg, k)} \\\\")
t.append(r"\midrule")
for k, lab in POOLED:
    t.append(f"{lab} & -- & {pm(cfg, k, 'final_s11_mae')} & -- & -- & {pm(cfg, k, 'final_s11_r2')} & -- & "
             f"{mn(cfg, k, 'final_gain_mae')} & {mn(cfg, k, 'final_fr_mape')} & {params(cfg, k)} \\\\")
c = S["data"]["ceiling"]["T5"]
t.append(f"Replicate limit$^\\dagger$ & -- & ${c['mae_mean']:.2f}$ & -- & -- & ${c['mean']:.3f}$ & -- & -- & -- & -- \\\\")
t += [r"\bottomrule", r"\end{tabular}"]
(OUT / "tab_t5.tex").write_text("\n".join(t) + "\n")

t = [r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
     r" & \multicolumn{2}{c}{$T=10$} & \multicolumn{2}{c}{$T=20$} \\",
     r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
     r"Method & Final\,$\downarrow$ & $\Delta$\,$\downarrow$ & Final\,$\downarrow$ & $\Delta$\,$\downarrow$ \\", r"\midrule"]
for k, lab in ROWS:
    t.append(f"{lab} & {pm('T10_e300', k, 'final_s11_mae')} & {mn('T10_e300', k, 'bwt_s11_mae')} & "
             f"{pm('T20_e300', k, 'final_s11_mae')} & {mn('T20_e300', k, 'bwt_s11_mae')} \\\\")
t.append(r"\midrule")
for k, lab in POOLED:
    t.append(f"{lab} & {pm('T10_e300', k, 'final_s11_mae')} & -- & {pm('T20_e300', k, 'final_s11_mae')} & -- \\\\")
c10, c20 = S["data"]["ceiling"]["T10"], S["data"]["ceiling"]["T20"]
t.append(f"Replicate limit$^\\dagger$ & ${c10['mae_mean']:.2f}$ & -- & ${c20['mae_mean']:.2f}$ & -- \\\\")
t += [r"\bottomrule", r"\end{tabular}"]
(OUT / "tab_long.tex").write_text("\n".join(t) + "\n")

t = [r"\begin{tabular}{@{}lccc@{}}", r"\toprule",
     r"Method & 30 epochs & 100 epochs & 300 epochs \\", r"\midrule"]
for k, lab in [("finetune", "MLP, fine-tuned"), ("ewc_best", "EWC, best $\\lambda$"),
               ("replay_buf0.1", "Replay, 10\\,\\%"), ("indep", "Independent MLPs"),
               ("cms", "NestAnt-CMS"), ("prognet", "Progressive Nets")]:
    t.append(f"{lab} & " + " & ".join(pm(f"T5_e{e}", k, "final_s11_mae") for e in (30, 100, 300)) + r" \\")
t += [r"\bottomrule", r"\end{tabular}"]
(OUT / "tab_budget.tex").write_text("\n".join(t) + "\n")
print("wrote", sorted(p.name for p in OUT.iterdir()))
